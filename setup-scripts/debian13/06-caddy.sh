#!/usr/bin/env bash
# 06 — Caddy: installs Caddy from the official repo and configures it as a reverse
# proxy with automatic HTTPS (Let's Encrypt) in front of uvicorn on 127.0.0.1.
# Caddy handles certificate issuance and renewal on its own. Idempotent.
#
# PREREQUISITE: the DNS of $DOMAIN must resolve to this VPS's public IP,
# or Caddy cannot complete the ACME challenge. Check with:
#   dig +short $DOMAIN
set -euo pipefail
source "$(dirname "$0")/lib.sh"
need_root "$@"
load_env

step "06 · Caddy (reverse proxy + auto-HTTPS)"

if ! command -v caddy >/dev/null 2>&1; then
    log "Adding the official Caddy repo…"
    apt_install debian-keyring debian-archive-keyring apt-transport-https
    curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' \
        | gpg --batch --yes --dearmor -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
    curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' \
        > /etc/apt/sources.list.d/caddy-stable.list
    apt-get update -y
    log "Installing Caddy…"
    apt_install caddy
else
    ok "Caddy already installed: $(caddy version | head -n1)"
fi

# Early warning if the DNS does not point here yet (does not abort: it may still propagate).
if command -v dig >/dev/null 2>&1; then
    resolved="$(dig +short "$DOMAIN" | tail -n1 || true)"
    [ -n "$resolved" ] \
        && log "DNS of $DOMAIN → $resolved" \
        || warn "dig does not resolve $DOMAIN yet. Caddy will retry ACME until it propagates."
fi

# Body limits: the same numbers as the app (server/orcaster_server/config.py); the
# app enforces them anyway without the proxy, so Caddy only cuts earlier. Each
# value is resolved with the precedence server/.env > setup.env > default (see
# resolve_limit in lib.sh): server/.env is what the app really reads, so it wins
# over setup.env (03 propagates the declared ones there). The defaults live in
# lib.sh, not here. A value that is not a positive integer aborts (die) before
# touching the Caddyfile.
#
# A key declared in setup.env but absent from server/.env (03 was not re-run
# after editing setup.env) would be applied by Caddy while the app keeps its
# default: explicit warning (does not abort; the Caddyfile keeps the setup.env
# value).
guard_server_env || true   # aborts here if it is a link or not a regular file
for key in "${BODY_LIMIT_KEYS[@]}"; do
    if [ -n "${!key+x}" ] && ! server_env_value "$key" >/dev/null 2>&1; then
        warn "$key is declared in setup.env but not in $SERVER_ENV: Caddy will use the setup.env value and the app will keep its default. Re-run 03-app-install.sh so the app matches."
    fi
done
resolve_limit MAX_BODY MAX_REQUEST_BODY_BYTES "$DEFAULT_MAX_REQUEST_BODY_BYTES"
resolve_limit MAX_OUTPUT_BODY MAX_OUTPUT_BODY_BYTES "$DEFAULT_MAX_OUTPUT_BODY_BYTES"
resolve_limit ART_TOTAL ARTIFACT_MAX_TOTAL_BYTES "$DEFAULT_ARTIFACT_MAX_TOTAL_BYTES"
resolve_limit ART_FILE ARTIFACT_MAX_FILE_BYTES "$DEFAULT_ARTIFACT_MAX_FILE_BYTES"
resolve_limit ART_OVERHEAD ARTIFACT_UPLOAD_OVERHEAD_BYTES "$DEFAULT_ARTIFACT_UPLOAD_OVERHEAD_BYTES"
# Artifact upload: the larger of TOTAL and FILE, plus the multipart overhead.
MAX_ARTIFACT_BODY="$(( (ART_TOTAL > ART_FILE ? ART_TOTAL : ART_FILE) + ART_OVERHEAD ))"
log "Body limits (bytes): default=${MAX_BODY} output=${MAX_OUTPUT_BODY} artifacts=${MAX_ARTIFACT_BODY}"

# Caddyfile. CADDYFILE_OVERRIDE is only used by the bats tests (like
# ENV_FILE_OVERRIDE in lib.sh); in the deploy it is /etc/caddy/Caddyfile.
CADDYFILE="${CADDYFILE_OVERRIDE:-/etc/caddy/Caddyfile}"

# Safe install: it is rendered to a temporary file in the same directory,
# validated there and only then replaces the Caddyfile (mv, atomic because it is on
# the same filesystem). If validation fails the current Caddyfile stays intact.
log "Writing ${CADDYFILE}…"
caddyfile_tmp="$(mktemp "${CADDYFILE}.XXXXXX")"
trap 'rm -f "$caddyfile_tmp"' EXIT
# Note: the heredoc is UNQUOTED, so every dollar sign, backtick and backslash is
# interpreted. Caddyfile comments must not contain backticks (they would run the
# text as a command) and the regexp's literal dollar sign is escaped with a
# backslash.
cat > "$caddyfile_tmp" <<EOF
# Generated by setup-scripts/debian13/06-caddy.sh
{
    email ${ADMIN_EMAIL}
}

${DOMAIN} {
    encode zstd gzip

    # HSTS: the browser uses HTTPS for this host for one year. Without
    # includeSubDomains or preload: it does not commit other subdomains or the
    # browser's preload list.
    header Strict-Transport-Security "max-age=31536000"

    # One request_body per handle, never a global one: Caddy stacks them and the
    # smaller one would also win over the upload routes. The two routes that
    # upload data have a higher limit than the rest.
    @artifacts path_regexp ^/v1/tasks/[0-9]+/artifacts\$
    handle @artifacts {
        request_body {
            max_size ${MAX_ARTIFACT_BODY}
        }
        reverse_proxy 127.0.0.1:${BIND_PORT}
    }
    @output path_regexp ^/v1/tasks/[0-9]+/output\$
    handle @output {
        request_body {
            max_size ${MAX_OUTPUT_BODY}
        }
        reverse_proxy 127.0.0.1:${BIND_PORT}
    }
    handle {
        request_body {
            max_size ${MAX_BODY}
        }
        reverse_proxy 127.0.0.1:${BIND_PORT}
    }
}
EOF

log "Validating configuration…"
if ! caddy validate --config "$caddyfile_tmp" --adapter caddyfile; then
    die "The generated Caddyfile does not validate; $CADDYFILE is left unchanged."
fi
# mktemp creates 0600; the caddy user must be able to read the file (it was 0644).
chmod 644 "$caddyfile_tmp"
# The current one is kept as ${CADDYFILE}.prev; if caddy cannot reload with the
# new one (reload and restart both fail) it is restored and the script exits
# with an error.
install_caddyfile "$caddyfile_tmp" "$CADDYFILE"

if [ -n "${CADDYFILE_OVERRIDE:-}" ]; then
    # Test mode: the destination is not the real Caddyfile, so the host's caddy
    # service is not touched.
    log "CADDYFILE_OVERRIDE set (tests only): skipping systemctl enable/reload/restart."
    ok "Caddyfile written to $CADDYFILE (caddy not reloaded)"
else
    caddy_activate_or_rollback "$CADDYFILE"
    ok "Caddyfile installed at $CADDYFILE"
    ok "Caddy serving https://${DOMAIN} → 127.0.0.1:${BIND_PORT}"
fi
