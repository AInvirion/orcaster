#!/usr/bin/env bash
# 01 — PostgreSQL: installs PG (17 in Trixie's base repos), starts the service
# and creates the role + database. Idempotent. If DB_PASSWORD is empty in
# setup.env, it generates a strong password and persists it back.
set -euo pipefail
source "$(dirname "$0")/lib.sh"
need_root "$@"
load_env

step "01 · PostgreSQL"

log "Installing PostgreSQL (server + contrib + client)…"
# Trixie ships PostgreSQL 17 in main → no PGDG repo needed. (Debian 12 needed it.)
apt_install postgresql postgresql-contrib

log "Enabling and starting postgresql…"
systemctl enable --now postgresql

# Password: autogenerate if missing and persist it so reruns are idempotent.
if [ -z "${DB_PASSWORD:-}" ]; then
    log "DB_PASSWORD empty → generating a strong password…"
    DB_PASSWORD="$(openssl rand -base64 24 | tr -d '/+=' | head -c 32)"
    persist_env DB_PASSWORD "$DB_PASSWORD"
    ok "Password generated and saved to setup.env."
fi

# psql as the 'postgres' system user (local peer auth). The `cd /` is the same
# guard as as_app: sudo inherits the caller's cwd, and from /root (mode 700)
# psql prints `could not change directory to "/root"` on every invocation. Here
# it degrades to noise rather than a failure, but it is noise that shows up in
# the middle of the deploy and sends you to diagnose the wrong postgres.
#
# A failure (sudo missing, postgres down) leaves an installer error and
# returns psql's exit code. Standalone calls stop the step through set -e.
psql_su() {
    require_sudo
    local rc=0
    ( cd / && sudo -u postgres psql -v ON_ERROR_STOP=1 "$@" ) || rc=$?
    [ "$rc" -eq 0 ] || err "psql as 'postgres' failed (exit $rc)."
    return "$rc"
}

# Existence probe: 0 if the query returns 1, 1 if it returns nothing.
# It is not written as `if psql_su … | grep -q 1`: inside an `if`, set -e does
# not apply and the pipe takes grep's exit code, so a broken psql_su was read as
# "does not exist" and the step went on to create the role. Here a failure stops
# the step.
pg_exists() {  # $1=SELECT 1 … query  $2=what is being looked up (for the message)
    local out rc=0
    out="$(psql_su -tAc "$1")" || rc=$?
    [ "$rc" -eq 0 ] || die "Could not query $2 in PostgreSQL (psql as 'postgres', exit $rc). 01 stops without creating anything."
    [ "$out" = "1" ]
}

# Role: create if missing; in any case set the password to the one in setup.env.
if pg_exists "SELECT 1 FROM pg_roles WHERE rolname='$DB_USER'" "whether role '$DB_USER' exists"; then
    ok "Role '$DB_USER' already exists."
else
    log "Creating role '$DB_USER'…"
    psql_su -c "CREATE ROLE \"$DB_USER\" LOGIN;"
fi
# Set the password by embedding it as an SQL literal with single quotes doubled
# (standard escape). Robust for any value: expanding "$esc_pwd" in the shell does
# not re-interpret the value's metacharacters, and doubling the quotes keeps the
# SQL literal intact. (The autogenerated one is alphanumeric.)
esc_pwd=${DB_PASSWORD//\'/\'\'}
psql_su -c "ALTER ROLE \"$DB_USER\" WITH PASSWORD '$esc_pwd';" >/dev/null
log "Role password synchronized with setup.env."

# Database: create if missing, with the role as owner.
if pg_exists "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" "whether database '$DB_NAME' exists"; then
    ok "Database '$DB_NAME' already exists."
else
    log "Creating database '$DB_NAME' (owner=$DB_USER)…"
    psql_su -c "CREATE DATABASE \"$DB_NAME\" OWNER \"$DB_USER\";"
fi

# Smoke: local TCP connection with the real password (what asyncpg will use).
if PGPASSWORD="$DB_PASSWORD" psql -h 127.0.0.1 -U "$DB_USER" -d "$DB_NAME" \
        -tAc "SELECT 'pong'" 2>/dev/null | grep -q pong; then
    ok "TCP connection 127.0.0.1:5432 verified for '$DB_USER'."
else
    die "Could not connect to the DB over TCP. Check pg_hba.conf (scram/md5 on local host)."
fi
