#!/usr/bin/env bash
# 07 — Hardening: firewall (ufw, only 22/80/443) and sshd hardening.
# Idempotent. For safety, it does NOT disable password login unless it detects
# at least one authorized SSH key — this avoids locking you out of the VPS.
set -euo pipefail
source "$(dirname "$0")/lib.sh"
need_root "$@"
load_env

step "07 · Firewall + SSH hardening"

# --- Firewall (ufw) -----------------------------------------------------------
command -v ufw >/dev/null 2>&1 || { log "Installing ufw…"; apt_install ufw; }

log "Firewall rules: allow SSH (22), HTTP (80) and HTTPS (443)…"
ufw allow 22/tcp   >/dev/null
ufw allow 80/tcp   >/dev/null
ufw allow 443/tcp  >/dev/null
ufw default deny incoming  >/dev/null
ufw default allow outgoing >/dev/null
# --force: enables without an interactive prompt (which would cut the SSH session).
ufw --force enable >/dev/null
ok "Firewall active (22/80/443 open, everything else denied)."

# --- SSH hardening ------------------------------------------------------------
# Is there any authorized public key? If not, disabling passwords = lockout.
has_keys=0
for f in /root/.ssh/authorized_keys /home/*/.ssh/authorized_keys; do
    [ -s "$f" ] && { has_keys=1; break; }
done

DROPIN=/etc/ssh/sshd_config.d/99-orcaster-hardening.conf
if [ "$has_keys" -eq 1 ]; then
    log "Authorized SSH keys detected → hardening sshd…"
    cat > "$DROPIN" <<'EOF'
# Generated by setup-scripts/debian13/07-firewall-ssh.sh
PermitRootLogin prohibit-password
PasswordAuthentication no
KbdInteractiveAuthentication no
EOF
    # Validate before reloading so the daemon is not broken.
    if sshd -t 2>/dev/null; then
        systemctl reload ssh 2>/dev/null || systemctl reload sshd 2>/dev/null || true
        ok "sshd hardened: key authentication only (root without password)."
    else
        rm -f "$DROPIN"
        warn "sshd -t failed; the drop-in was reverted. SSH unchanged."
    fi
else
    warn "No ~/.ssh/authorized_keys with keys found. NOT disabling password"
    warn "login so as not to lock you out. Upload your key (ssh-copy-id) and run"
    warn "this script again to complete the SSH hardening."
fi
