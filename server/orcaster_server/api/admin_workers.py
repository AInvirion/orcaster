"""Endpoints `/admin/workers/*`.

Admin operations on workers: pause/resume/clear-cache/delete. The `reason` of
pause/resume is not persisted in `workers` (the model has no dedicated column):
it goes to `admin_actions.reason`, where the "why" of the action lives.
"""

from __future__ import annotations

import json
import uuid as uuid_pkg
from datetime import UTC, datetime
from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException, Request, Response, status
from pydantic import BaseModel, Field, field_validator
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from orcaster_server.api._reason import reason_from_request
from orcaster_server.audit import record_admin_action
from orcaster_server.db import get_session
from orcaster_server.deps import WorkspaceContext, require_workspace_owner
from orcaster_server.env_names import validate_payload_egress_allowlist, validate_payload_task_env
from orcaster_server.signing import (
    get_private_key,
    is_signing_configured,
    sign_task,
    signature_to_b64,
)

router = APIRouter(prefix="/admin/workers", tags=["admin"])

SessionDep = Annotated[AsyncSession, Depends(get_session)]
# Worker control (pause, resume, clear-cache, delete, command) is owner-only.
OwnerDep = Annotated[WorkspaceContext, Depends(require_workspace_owner)]


class _PauseBody(BaseModel):
    # Body of pause and resume: both accept the same optional reason.
    reason: str | None = None


# --- SQL --------------------------------------------------------------------

# The canonical worker lookup for admin operations filters
# `deleted_at IS NULL`. A soft-deleted worker is not paused/resumed; the
# detail view stays accessible (another route, another SQL).
_SQL_GET_WORKER_STATUS = text(
    "SELECT status FROM workers WHERE id = :id AND deleted_at IS NULL "
    "AND workspace_id = :workspace_id"
)

# Variant for the DELETE endpoint: tells "never existed" (404) apart from
# "already soft-deleted" (idempotent, silent 204). Returns the soft-delete
# mark along with the status so the handler can decide. Scoped to the active
# workspace: a worker of another tenant yields 404 (does not exist).
_SQL_GET_WORKER_FOR_DELETE = text(
    "SELECT status, deleted_at FROM workers WHERE id = :id AND workspace_id = :workspace_id"
)

_SQL_PAUSE_WORKER = text(
    """
    UPDATE workers SET status = 'paused'
     WHERE id = :id AND status = 'online' AND deleted_at IS NULL
       AND workspace_id = :workspace_id
    RETURNING 1
    """
)

_SQL_RESUME_WORKER = text(
    """
    UPDATE workers SET status = 'online'
     WHERE id = :id AND status = 'paused' AND deleted_at IS NULL
       AND workspace_id = :workspace_id
    RETURNING 1
    """
)

# Soft-cancel of the worker's non-terminal executions before deleting it
# (`?force=true` path).
_SQL_FORCE_CANCEL_EXECUTIONS = text(
    """
    UPDATE task_executions
       SET status = 'cancelled', finished_at = now()
     WHERE worker_id = :id
       AND status IN ('assigned', 'claimed', 'running')
    """
)

# Soft-delete. The row is NOT deleted; it is marked `deleted_at = now()`.
# The `deleted_at IS NULL` predicate makes the operation idempotent: a second
# DELETE on an already soft-deleted worker affects no rows (empty RETURNING,
# but the endpoint still responds 204).
_SQL_SOFT_DELETE_WORKER = text(
    """
    UPDATE workers
       SET deleted_at = now()
     WHERE id = :id AND deleted_at IS NULL AND workspace_id = :workspace_id
    RETURNING 1
    """
)

# Cancels, in the same transaction, the pending push tasks aimed at the
# deleted worker. Pull tasks (delivery_mode='claim') or tasks whose
# target_worker_pool includes the worker are NOT touched: they may go to other
# workers of the pool and the normal fan-out close resolves them.
_SQL_CANCEL_PUSH_TASKS_FOR_WORKER = text(
    """
    UPDATE tasks
       SET status = 'cancelled',
           completed_at = now(),
           cancelled_reason = 'target_worker_deleted'
     WHERE delivery_mode = 'push'
       AND target_worker_id = :id
       AND workspace_id = :workspace_id
       AND status NOT IN ('completed', 'failed', 'cancelled')
    """
)

_SQL_WORKER_EXISTS = text(
    "SELECT 1 FROM workers WHERE id = :id AND deleted_at IS NULL AND workspace_id = :workspace_id"
)

_SQL_CLEAR_CACHE = text(
    "UPDATE workers SET cache_flush_requested_at = now() "
    "WHERE id = :id AND deleted_at IS NULL AND workspace_id = :workspace_id"
)

# Push commands are tasks with `delivery_mode='push'` signed with Ed25519.
# Two steps: INSERT without a signature to obtain `task_id` (autogenerated
# bigserial), sign the canonical_json over
# {command, created_at, idempotency_key, payload, task_id, worker_id}, then
# UPDATE with the signature. The transaction is committed at the end.
_SQL_INSERT_PUSH_TASK_UNSIGNED = text(
    """
    INSERT INTO tasks (command, payload, target_mode, target_count, eligibility,
                       claim_timeout_seconds, status, priority, run_at,
                       delivery_mode, target_worker_id, signed, signature,
                       idempotency_key, expires_at, workspace_id)
    VALUES (:command, CAST(:payload AS jsonb), 'count', 1, '{}'::jsonb,
            NULL, 'queued', 0, now(),
            'push', :target_worker_id, true, decode(repeat('00', 64), 'hex'),
            :idempotency_key, :expires_at, :workspace_id)
    RETURNING id, created_at
    """
)

# Universal signature: `signature` is NOT NULL. We insert a 64-byte
# placeholder and overwrite it with the real signature in the same
# transaction.

_SQL_UPDATE_TASK_SIGNATURE = text(
    """
    UPDATE tasks SET signed = true, signature = :signature
     WHERE id = :task_id
    """
)


class _CommandBody(BaseModel):
    command: str = Field(min_length=1, max_length=64)
    payload: dict | None = None
    expires_at: datetime

    @field_validator("payload")
    @classmethod
    def _validate_isolation_fields(cls, v: dict | None) -> dict | None:
        """Same shape rules as creating a task: `payload.task_env` and
        `payload.egress_allowlist`. The worker runs a non-reserved command
        with `_run_external`, which reads both keys."""
        if v is not None:
            validate_payload_task_env(v)
            validate_payload_egress_allowlist(v)
        return v


# --- Endpoints --------------------------------------------------------------


# auth: owner-only (require_workspace_owner)
@router.post("/{worker_id}/pause")
async def admin_pause_worker(
    worker_id: str,
    request: Request,
    session: SessionDep,
    ctx: OwnerDep,
    body: _PauseBody | None = None,
) -> dict[str, str]:
    row = (
        await session.execute(
            _SQL_GET_WORKER_STATUS, {"id": worker_id, "workspace_id": ctx.workspace_id}
        )
    ).first()
    if row is None:
        raise HTTPException(status_code=404, detail="worker not found")
    if row[0] != "online":
        raise HTTPException(
            status_code=409,
            detail=f"worker in status '{row[0]}' cannot be paused",
        )
    # The UPDATE re-checks `status='online'` in its WHERE: if housekeeping
    # (or another operator) changed it between the SELECT above and this point,
    # the RETURNING comes back empty and nothing is audited; a 200 with an audit
    # row here would record a pause that never happened.
    paused = (
        await session.execute(
            _SQL_PAUSE_WORKER, {"id": worker_id, "workspace_id": ctx.workspace_id}
        )
    ).first()
    if paused is None:
        raise HTTPException(
            status_code=409,
            detail="worker status changed concurrently; pause not applied",
        )
    # Audit before the commit and in the same transaction (contract of
    # orcaster_server/audit.py). `prior_status` follows the delete_worker
    # precedent. `actor`: passed by the caller, which knows the session (the
    # helper does not derive it). Same pattern as the credential actions in
    # admin_ui.py and the other two worker actions in this same file
    # (delete_worker, clear_worker_cache), so the audit log is symmetric.
    await record_admin_action(
        session,
        workspace_id=ctx.workspace_id,
        action="pause_worker",
        target_kind="worker",
        target_id=worker_id,
        reason=reason_from_request(request, body.reason if body is not None else None),
        actor=ctx.user.id,
        payload={"prior_status": row[0]},
    )
    await session.commit()
    return {"status": "paused"}


# auth: owner-only (require_workspace_owner)
@router.post("/{worker_id}/resume")
async def admin_resume_worker(
    worker_id: str,
    request: Request,
    session: SessionDep,
    ctx: OwnerDep,
    body: _PauseBody | None = None,
) -> dict[str, str]:
    row = (
        await session.execute(
            _SQL_GET_WORKER_STATUS, {"id": worker_id, "workspace_id": ctx.workspace_id}
        )
    ).first()
    if row is None:
        raise HTTPException(status_code=404, detail="worker not found")
    if row[0] != "paused":
        raise HTTPException(
            status_code=409,
            detail=f"worker in status '{row[0]}' cannot be resumed",
        )
    # Same race guard as pause: empty RETURNING = the status was no longer
    # 'paused' at UPDATE time -> 409 with no audit row.
    resumed = (
        await session.execute(
            _SQL_RESUME_WORKER, {"id": worker_id, "workspace_id": ctx.workspace_id}
        )
    ).first()
    if resumed is None:
        raise HTTPException(
            status_code=409,
            detail="worker status changed concurrently; resume not applied",
        )
    await record_admin_action(
        session,
        workspace_id=ctx.workspace_id,
        action="resume_worker",
        target_kind="worker",
        target_id=worker_id,
        reason=reason_from_request(request, body.reason if body is not None else None),
        actor=ctx.user.id,
        payload={"prior_status": row[0]},
    )
    await session.commit()
    return {"status": "online"}


# auth: owner-only (require_workspace_owner)
@router.post("/{worker_id}/clear-cache")
async def admin_clear_worker_cache(
    worker_id: str,
    session: SessionDep,
    ctx: OwnerDep,
) -> dict[str, str]:
    row = (
        await session.execute(
            _SQL_GET_WORKER_STATUS, {"id": worker_id, "workspace_id": ctx.workspace_id}
        )
    ).first()
    if row is None:
        raise HTTPException(status_code=404, detail="worker not found")
    # No status guard: it can be requested even if the worker is offline/busy;
    # the poll delivers the signal when the worker comes back and reports idle
    # (defer until idle).
    await session.execute(_SQL_CLEAR_CACHE, {"id": worker_id, "workspace_id": ctx.workspace_id})
    await record_admin_action(
        session,
        workspace_id=ctx.workspace_id,
        action="clear_worker_cache",
        target_kind="worker",
        target_id=worker_id,
        actor=ctx.user.id,
    )
    await session.commit()
    return {"status": "requested"}


# auth: owner-only (require_workspace_owner)
@router.delete("/{worker_id}", status_code=status.HTTP_204_NO_CONTENT)
async def admin_delete_worker(
    worker_id: str,
    session: SessionDep,
    ctx: OwnerDep,
    force: bool = False,
) -> Response:
    """Soft-delete the worker.

    Deleting a worker does not remove the row (a hard delete would cascade
    through `ON DELETE CASCADE` and wipe `task_executions`, losing history).
    It sets `deleted_at = now()` and, in the same transaction:

    - (`?force=true` only) soft-cancels the worker's active executions.
    - Soft-cancels the pending push tasks whose `target_worker_id` is this
      worker (with `cancelled_reason='target_worker_deleted'`), because
      without a target worker those tasks would be orphaned.

    Idempotent: if the worker was already soft-deleted, we respond 204
    silently without touching anything (the UPDATEs are not re-run and no
    second admin_action is recorded). 404 only if the row never existed.
    """
    row = (
        await session.execute(
            _SQL_GET_WORKER_FOR_DELETE, {"id": worker_id, "workspace_id": ctx.workspace_id}
        )
    ).first()
    if row is None:
        raise HTTPException(status_code=404, detail="worker not found")
    # Idempotent: already soft-deleted -> 204 with no side effects.
    if row[1] is not None:
        return Response(status_code=status.HTTP_204_NO_CONTENT)
    if not force and row[0] != "offline":
        raise HTTPException(
            status_code=409,
            detail=f"worker in status '{row[0]}' must be offline to delete (use ?force=true)",
        )
    if force:
        # Soft-cancel active executions before soft-deleting the worker.
        await session.execute(_SQL_FORCE_CANCEL_EXECUTIONS, {"id": worker_id})
    # Soft-delete + cancel of pending push tasks in the same transaction.
    await session.execute(
        _SQL_SOFT_DELETE_WORKER, {"id": worker_id, "workspace_id": ctx.workspace_id}
    )
    await session.execute(
        _SQL_CANCEL_PUSH_TASKS_FOR_WORKER, {"id": worker_id, "workspace_id": ctx.workspace_id}
    )
    await record_admin_action(
        session,
        workspace_id=ctx.workspace_id,
        action="delete_worker",
        target_kind="worker",
        target_id=worker_id,
        payload={"force": force, "prior_status": row[0]},
        actor=ctx.user.id,
    )
    await session.commit()
    return Response(status_code=status.HTTP_204_NO_CONTENT)


# auth: owner-only (require_workspace_owner)
@router.post("/{worker_id}/command")
async def admin_push_command(
    worker_id: str,
    body: _CommandBody,
    session: SessionDep,
    ctx: OwnerDep,
) -> dict[str, str]:
    """Enqueue an Ed25519-signed command as a push task.

    Push commands are regular tasks with `delivery_mode='push'`,
    `target_worker_id=<this worker>`, `signed=true`. The worker receives them
    through `/v1/workers/{id}/poll` like any other task, with the signature
    reconstructible over the 6 canonical fields.

    Two steps: INSERT without a signature to obtain `task_id` (bigserial), sign
    the canonical_json, UPDATE with the signature. All in one transaction.

    Returns `{task_id, signature, status}`; the `uuid` field is kept as an
    alias of the idempotency key for clients that still read it, but the
    canonical identity of the delivery is `task_id`.
    """
    exists = (
        await session.execute(
            _SQL_WORKER_EXISTS, {"id": worker_id, "workspace_id": ctx.workspace_id}
        )
    ).first()
    if exists is None:
        raise HTTPException(status_code=404, detail="worker not found")

    # If signing is not configured, this feature is disabled by config (not a
    # bug). We respond 503 with Retry-After to tell "feature off" apart from
    # "internal error".
    if not is_signing_configured():
        raise HTTPException(
            status_code=503,
            detail="push commands disabled: server has no Ed25519 signing key configured",
            headers={"Retry-After": "60"},
        )
    try:
        priv = get_private_key()
    except (RuntimeError, FileNotFoundError, OSError, ValueError) as exc:
        raise HTTPException(
            status_code=503,
            detail="push commands temporarily unavailable: signing key unreadable",
            headers={"Retry-After": "60"},
        ) from exc

    # Autogenerated idempotency key (uuid4). It lets admin retries with the
    # same key fail with UniqueViolation and avoid double deliveries.
    idempotency_key = str(uuid_pkg.uuid4())

    row = (
        await session.execute(
            _SQL_INSERT_PUSH_TASK_UNSIGNED,
            {
                "command": body.command,
                "payload": json.dumps(body.payload if body.payload is not None else {}),
                "target_worker_id": worker_id,
                "idempotency_key": idempotency_key,
                "expires_at": body.expires_at,
                "workspace_id": ctx.workspace_id,
            },
        )
    ).first()
    assert row is not None
    task_id = int(row[0])
    created_at: datetime = row[1]
    # Postgres returns a tz-aware datetime (timestamptz). If for some reason it
    # arrives naive, we localize it to UTC so isoformat matches what the client
    # will reconstruct after reading the row.
    if created_at.tzinfo is None:
        created_at = created_at.replace(tzinfo=UTC)
    # Pydantic v2 serializes a UTC datetime with a "Z" suffix in JSON. So the
    # client can rebuild the canonical message byte-for-byte, we sign with that
    # same representation. RFC 3339 allows both but the signature needs one.
    created_at_iso = created_at.isoformat().replace("+00:00", "Z")

    signature = sign_task(
        priv,
        task_id=task_id,
        worker_id=worker_id,
        command=body.command,
        payload=body.payload if body.payload is not None else {},
        idempotency_key=idempotency_key,
        created_at_iso=created_at_iso,
    )

    await session.execute(
        _SQL_UPDATE_TASK_SIGNATURE,
        {"signature": signature, "task_id": task_id},
    )
    await session.commit()

    return {
        "task_id": str(task_id),
        "uuid": idempotency_key,  # alias kept for clients that read `uuid`.
        "signature": signature_to_b64(signature),
        "idempotency_key": idempotency_key,
        "created_at": created_at_iso,
        "status": "pending",
    }
