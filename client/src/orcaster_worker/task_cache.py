"""Task-scoped scratch cache that persists between attempts of the same "job".

Motivation
----------
Large downloads (datasets, artifacts) get throttled. If a task fails halfway
and is retried, we do not want to download everything again from scratch. The
worker exposes a scratch directory per *job key* to the subprocess through the
``ORCASTER_CACHE_DIR`` env var; the script (or a wrapper) decides whether to
re-point ``PIP_CACHE_DIR``, ``XDG_CACHE_HOME``, etc. - this is not done
automatically because it would be an aggressive preset with consequences that
are hard to revert.

Layout
------
``<cache_root>/tasks/<key>/``

``key`` = ``idempotency_key`` if the task carries one, otherwise ``f"task-{task_id}"``.
The first lets server-side retries (same idempotency_key, different
execution) reuse scratch between themselves; the second gives per-task scratch with
no cross-task accumulation.

``<cache_root>/run/<unique>/``

Ephemeral working directory per execution. Created by
``create_execution_run_dir`` before each dispatch and removed right
after (via ``asyncio.to_thread(shutil.rmtree, ...)``) by
``_run_external``. It is outside the scope of the GC; any residual dir
(worker crash) is swept at startup via ``sweep_run_dirs``.

``<cache_root>/trash/<unique>/``

Detach area. Any deletion that can run in parallel with a job first
takes the tree out of the namespace with an ``os.replace`` and only then
runs the ``rmtree`` on the detached path. See ``_detach_for_delete``.
Leftovers from a crash halfway through the ``rmtree`` are swept by ``sweep_trash_dirs``.

GC
--
* **By age**: dirs whose ``mtime`` is older than ``max_age_days`` (default 3).
* **By disk pressure**: if ``free/total < min_free_fraction`` (default 20%),
  reactive LRU deleting dirs until ``recover_free_fraction`` (80%) is exceeded.

Neither pass touches the dir of the job the worker is running:
``run_gc`` receives that ``keep_job_key`` (a getter, never a frozen value: see
its docstring) and excludes it from the candidates, re-reading it before each deletion,
and **detaches** each victim from the namespace before deleting it, so that a
job that claims that key while the ``rmtree`` is still in flight gets an intact
fresh dir.
Corollary: pressure caused by the running job itself cannot be resolved by the
GC; it is reported in ``GcStats.pressure_unrecoverable``.

The GC runs periodically from the worker supervisor (asyncio loop in
``main.run``); this module is only pure logic, testable with a mockable ``shutil``.
"""

from __future__ import annotations

import contextlib
import logging
import os
import shutil
import stat
import tempfile
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path

log = logging.getLogger("orcaster.worker.task_cache")

_TASKS_SUBDIR = "tasks"
_RUN_SUBDIR = "run"
_TRASH_SUBDIR = "trash"
# Prefix of the holders created by `_detach_for_delete`. `sweep_trash_dirs` sweeps
# only what starts with this: `base` may be an operator directory.
_TRASH_HOLDER_PREFIX = "gone-"


def _tasks_root(cache_root: Path) -> Path:
    return cache_root / _TASKS_SUBDIR


def _run_root(cache_root: Path) -> Path:
    return cache_root / _RUN_SUBDIR


def trash_root(base: Path) -> Path:
    """Detach area of ``base``. It must live on the SAME filesystem as what
    will be detached: ``os.replace`` does not cross devices (EXDEV)."""
    return base / _TRASH_SUBDIR


def _safe_key(key: str) -> str:
    """Sanitize ``key`` for use as a directory name."""
    cleaned = "".join(c if c.isalnum() or c in "-_." else "_" for c in key)
    return cleaned[:128] or "_"


def resolve_job_key(*, idempotency_key: str | None, task_id: int) -> str:
    """Decide the cache key. idempotency_key wins; falls back to task_id."""
    if idempotency_key:
        return _safe_key(idempotency_key)
    return f"task-{task_id}"


def ensure_task_cache_dir(cache_root: Path, key: str) -> Path:
    """Create (idempotently) the task scratch dir and refresh its mtime.

    Touching the dir is what moves the LRU; without it, the GC could
    sweep an active job between attempts if the first attempt is old.
    """
    tasks_root = _tasks_root(cache_root)
    tasks_root.mkdir(parents=True, exist_ok=True)
    safe = _safe_key(key)
    path = tasks_root / safe
    path.mkdir(parents=True, exist_ok=True)
    # mtime bump: use utime so no extra files are created inside.
    os.utime(path, None)
    return path


def create_execution_run_dir(cache_root: Path, *, task_id: int) -> Path:
    """Create a unique ephemeral working directory for a task execution.

    The directory is located in ``<cache_root>/run/`` and uses a
    ``task-{task_id}-`` prefix followed by a unique suffix generated by
    ``tempfile.mkdtemp``. The caller is responsible for removing it after the
    dispatch (with ``shutil.rmtree``); ``sweep_run_dirs`` cleans leftovers at
    startup.
    """
    run_root = _run_root(cache_root)
    run_root.mkdir(parents=True, exist_ok=True)
    return Path(tempfile.mkdtemp(dir=run_root, prefix=f"task-{task_id}-"))


def sweep_run_dirs(cache_root: Path) -> int:
    """Sweep the residual subdirectories of ``<cache_root>/run/`` at startup.

    Called once during worker startup to remove ephemeral directories of
    previous executions that were not cleaned up (e.g. after a
    crash). Returns the number of subdirs removed. If ``<cache_root>/run/``
    does not exist, returns 0 without error.
    """
    run_root = _run_root(cache_root)
    if not run_root.exists():
        return 0
    count = 0
    for entry in run_root.iterdir():
        if entry.is_dir():
            shutil.rmtree(entry, ignore_errors=True)
            count += 1
    if count:
        log.info("sweep_run_dirs: removed %d residual ephemeral dir(s) in %s", count, run_root)
    return count


@dataclass(frozen=True)
class GcStats:
    """Result of a GC pass (useful for logging and tests)."""

    scanned: int
    deleted_age: int
    deleted_pressure: int
    bytes_freed_estimate: int
    free_before: int
    free_after: int
    skipped_active: int = 0
    pressure_unrecoverable: bool = False


@dataclass(frozen=True)
class ResetStats:
    """Result of a cache reset of other jobs (useful for logging and tests)."""

    dirs_deleted: int
    bytes_freed_est: int
    failed_dirs: tuple[Path, ...]


def _dir_mtime(path: Path) -> float:
    try:
        return path.stat().st_mtime
    except OSError:
        return 0.0


def _dir_size_estimate(path: Path) -> int:
    """Quick sum of file sizes in the subtree. Errors are ignored.

    Symlinks are skipped: content-addressed caches expose each file as a
    symlink to a blob (e.g. ``blobs/<sha>``), so following them counted the same
    byte twice and inflated ``bytes_freed`` to ~2x the real size.
    """
    total = 0
    try:
        for p in path.rglob("*"):
            try:
                st = p.lstat()
            except OSError:
                continue
            # lstat does not follow the link, so the symlink is discarded for not being
            # a regular file: a single syscall per entry instead of three
            # (is_symlink + is_file + stat) on trees of ~100k entries.
            if stat.S_ISREG(st.st_mode):
                total += st.st_size
    except OSError:
        return total
    return total


def _detach_for_delete(path: Path, base: Path) -> Path:
    """Take ``path`` out of the visible namespace with an atomic rename.

    Returns the detached path, or ``path`` untouched if the rename was not
    possible. The destination is ``<base>/trash/<unique>/<name>``: ``mkdtemp`` gives
    uniqueness atomically (two concurrent deleters - the GC and the flush do not
    coordinate - never pick the same holder) and the name inside the holder
    is guaranteed to be free.

    Why a rename and not a direct ``rmtree``: the ``rmtree`` of a multi-GB tree
    runs for minutes, and during those minutes the path stays in the namespace
    where the worker creates the scratch of the job that claims that same key. The
    ``keep_job_key`` guard only covers the deletion that has not started yet; one
    in flight had no protection at all, and took away the files the task had
    just downloaded (same symptom, through another door). With the
    detach, the deletion operates on a tree nobody else can reach.

    A residual window remains between the ``keep_job_key`` check and this
    ``os.replace``, the width of a function return. It is accepted: closing it
    would require a lock shared between the event loop and the GC threads, which
    is not worth it for microseconds.

    The in-place fallback is deliberate: losing the protection is preferable to
    not recovering disk (the caller only deletes when the space is needed).

    ``FileNotFoundError`` is the only failure that is NOT reported as loss of
    protection: the tree is already gone, so there was nothing to protect and the
    caller ``rmtree`` will be a no-op. It happens in a benign and expected race:
    the GC enumerates candidates under ``tasks/`` and ``flush_caches``
    detaches the whole ``tasks/`` from another thread before the GC reaches
    one. A WARNING there trains the operator to ignore the one that does matter (EXDEV,
    permissions), which is the case where the deletion really runs unprotected.
    """
    holder: Path | None = None
    try:
        root = trash_root(base)
        root.mkdir(parents=True, exist_ok=True)
        holder = Path(tempfile.mkdtemp(dir=root, prefix=_TRASH_HOLDER_PREFIX))
        target = holder / path.name
        os.replace(path, target)
    except OSError as e:
        if holder is not None:
            with contextlib.suppress(OSError):
                holder.rmdir()
        if isinstance(e, FileNotFoundError):
            log.debug(
                "task_cache: %s no longer exists when detaching it (%s); nothing to delete",
                path,
                e,
            )
        else:
            log.warning(
                "task_cache: could not detach %s before deleting it (%s); "
                "deleting in place (without the detach protection)",
                path,
                e,
            )
        return path
    return target


def _delete_dir(path: Path, *, detach_base: Path | None = None) -> int:
    """Delete the subtree; return estimated bytes freed (best-effort).

    With ``detach_base``, the tree leaves the namespace before being deleted.
    The ``rmtree`` is still synchronous: a caller that measures disk after
    each deletion (the pressure pass) sees the space already recovered.

    Order matters: the rename goes BEFORE ``_dir_size_estimate``. Estimating
    first would leave the ``rglob`` (minutes over ~100k entries) running with the
    dir still in the namespace, i.e. the same window the detach closes.
    """
    target = path if detach_base is None else _detach_for_delete(path, detach_base)
    size = _dir_size_estimate(target)
    shutil.rmtree(target, ignore_errors=True)
    if target != path:
        # The holder is empty after the rmtree; without this the detach area
        # would accumulate one dir per deletion until the next sweep.
        with contextlib.suppress(OSError):
            target.parent.rmdir()
    return size


def sweep_trash_dirs(base: Path) -> int:
    """Sweep the residual detached trees of ``<base>/trash/`` at startup.

    Symmetric to ``sweep_run_dirs``: the detach deletes synchronously, so
    all that remains there is what a crash (or a SIGKILL) left halfway through the
    ``rmtree``. Nobody else will look at it - the GC only enumerates ``tasks/`` - so
    without this sweep those GB are never recovered. Returns the dirs removed.

    It deletes **only** entries with the ``_detach_for_delete`` prefix, not everything
    under ``trash/``. The reason is that ``base`` is not always an orcaster tree:
    the worker-wide uv cache is detached in the parent of
    ``ORCH_ORCASTER_UV_CACHE_DIR``, which the operator chooses, and a
    pre-existing ``<that_parent>/trash`` with foreign content would be deleted by
    the worker startup. Sweeping only what we created is the only way
    this sweep cannot destroy anyone else's data.
    """
    root = trash_root(base)
    if not root.exists():
        return 0
    count = 0
    for entry in root.iterdir():
        if not entry.name.startswith(_TRASH_HOLDER_PREFIX):
            continue
        if entry.is_dir():
            shutil.rmtree(entry, ignore_errors=True)
            count += 1
        else:
            with contextlib.suppress(OSError):
                entry.unlink()
    if count:
        log.info("sweep_trash_dirs: removed %d detached tree(s) in %s", count, root)
    return count


def run_gc(
    cache_root: Path,
    *,
    max_age_days: int,
    min_free_fraction: float,
    recover_free_fraction: float,
    keep_job_key: Callable[[], str | None] | None = None,
    previously_unrecoverable: bool = False,
    now: datetime | None = None,
) -> GcStats:
    """Run one GC pass over ``<cache_root>/tasks/``.

    1. Delete dirs whose ``mtime`` exceeds ``max_age_days``.
    2. Measure ``shutil.disk_usage(cache_root)``; if ``free/total <
       min_free_fraction``, reactive LRU (oldest first) until
       ``recover_free_fraction`` is exceeded or the candidates run out.

    ``keep_job_key`` is the job the worker is running right now: its
    dir is left out of both passes. The GC runs in the same process and
    in parallel with the job, so without this exclusion the pressure branch
    deleted the dir the task is reading from, and the task died with
    ``FileNotFoundError`` on a file it had downloaded itself.
    Symmetric to ``keep_job_key`` of ``reset_other_job_caches``.

    It is a *callable* that returns the live key, and **only** a callable: the GC
    runs in a thread while the worker keeps claiming tasks, a pass lasts
    minutes (each ``_delete_dir`` is an ``rglob`` plus a multi-GB ``rmtree``) and
    with a ``str`` the exclusion would be frozen at the instant the pass started,
    so a job that starts midway would be left unprotected again. The key is
    re-read before **each** deletion, in both passes.

    A ``str`` is rejected: accepting it left the unsafe semantics (frozen
    exclusion) as a first-class calling convention, and a caller who read the type
    hint and passed the key at hand reintroduced the deletion of the live job dir
    without touching anything the tests cover. The check is at runtime because CI
    does not run a type checker, and it goes before any deletion: a contract
    violation must not be discovered midway through a pass.
    It also avoids re-evaluating ``callable(...)`` per entry inside ``_is_live``.

    Re-reading the key covers the deletion that has not started yet, not the one
    already in flight: the victim ``rmtree`` lasts minutes and the job that claims
    that key midway would write inside the tree the GC was still unlinking.
    That is why each victim is **detached** from the namespace before being deleted
    (``_detach_for_delete``): the in-flight deletion operates on a path that is no
    longer reachable, and a later claim gets a fresh dir.

    ``previously_unrecoverable`` is the value of ``GcStats.pressure_unrecoverable``
    from the previous tick: the WARNING is emitted only on the transition, not on
    every tick while the pressure persists.

    ``now`` is injectable for deterministic tests.
    """
    if keep_job_key is not None and not callable(keep_job_key):
        raise TypeError(
            "keep_job_key must be a callable that returns the live job key "
            f"(or None), not {type(keep_job_key).__name__}: a frozen value leaves "
            "a job claimed midway through a pass unprotected."
        )
    tasks_root = _tasks_root(cache_root)
    if not tasks_root.exists():
        # No-op if the cache was never used; keep the signature stable.
        try:
            usage = shutil.disk_usage(cache_root if cache_root.exists() else cache_root.parent)
            free_before = usage.free
        except OSError:
            free_before = 0
        return GcStats(
            scanned=0,
            deleted_age=0,
            deleted_pressure=0,
            bytes_freed_estimate=0,
            free_before=free_before,
            free_after=free_before,
        )

    now_dt = now or datetime.now(UTC)
    cutoff_ts = (now_dt - timedelta(days=max_age_days)).timestamp()

    all_dirs: list[Path] = [p for p in tasks_root.iterdir() if p.is_dir()]
    scanned = len(all_dirs)
    skipped_names: set[str] = set()

    def _is_live(entry: Path) -> bool:
        """Re-read the live key right before deleting ``entry``.

        Enumerating the candidates only once is correct (a dir created midway
        through the pass is not in the list), but the exclusion cannot be a
        snapshot: the live job changes while the pass runs. That is why the
        parameter is a callable and nothing else: the type already guarantees
        a fresh read here, with no per-entry dispatch.
        """
        raw = keep_job_key() if keep_job_key is not None else None
        keep = _safe_key(raw) if raw else None
        if keep is not None and entry.name == keep:
            skipped_names.add(entry.name)
            return True
        return False

    try:
        usage_before = shutil.disk_usage(cache_root)
        free_before = usage_before.free
        total = usage_before.total
    except OSError:
        free_before = 0
        total = 0

    deleted_age = 0
    bytes_freed = 0
    survivors: list[Path] = []
    for entry in all_dirs:
        if _is_live(entry):
            # It survives the age pass, but is still an LRU candidate:
            # the exclusion applies to deletion, not to the set. If the job
            # finishes between the two passes, removing it from `survivors` would leave the
            # GC declaring the pressure unrecoverable with a multi-GB candidate
            # available. The pressure pass re-reads `_is_live`.
            survivors.append(entry)
            continue
        mtime = _dir_mtime(entry)
        if mtime and mtime < cutoff_ts:
            bytes_freed += _delete_dir(entry, detach_base=cache_root)
            deleted_age += 1
        else:
            survivors.append(entry)

    deleted_pressure = 0
    pressure_triggered = total > 0 and free_before / total < min_free_fraction
    if pressure_triggered:
        # LRU: delete oldest first until the target is exceeded or we run out
        # of candidates. The usage is refreshed after each delete to
        # honor the target without over-deleting.
        survivors.sort(key=_dir_mtime)
        target = recover_free_fraction
        for entry in survivors:
            try:
                usage_now = shutil.disk_usage(cache_root)
            except OSError:
                break
            if usage_now.total > 0 and usage_now.free / usage_now.total >= target:
                break
            if _is_live(entry):
                # The job started after the candidates were enumerated: its dir is
                # exactly the one the LRU looks at last (fresh mtime), so this
                # is the long window for deleting the live job.
                continue
            # It was live in the age pass but no longer: if we delete it, it
            # was not a protected dir and must not count as one.
            skipped_names.discard(entry.name)
            bytes_freed += _delete_dir(entry, detach_base=cache_root)
            deleted_pressure += 1

    free_after_known = True
    try:
        free_after = shutil.disk_usage(cache_root).free
    except OSError:
        free_after = free_before
        free_after_known = False

    # The pressure is declared unrecoverable if after the pass we are still below the
    # trigger floor: with one live job per worker the only candidate is usually
    # its own dir, which is now excluded. The GC cannot resolve it
    # and says so in the log instead of staying silent; stopping the download is the job
    # of the next task disk preflight. The threshold is `min_free_fraction`,
    # not the target: ending between the floor and the target means the pressure
    # was resolved, and warning there would be a false alarm per tick.
    #
    # `free_after_known` avoids the false warning when the final `disk_usage` raises
    # OSError: the fallback leaves `free_after = free_before`, which is below the
    # floor by construction (it is the same comparison that triggered the pressure), and
    # without this guard a pass that did recover the disk would be reported as
    # unrecoverable with stale figures.
    skipped_active = len(skipped_names)
    pressure_unrecoverable = (
        pressure_triggered
        and free_after_known
        and total > 0
        and free_after / total < min_free_fraction
    )
    # Only on the transition: while the pressure persists, one WARNING per tick
    # (288 a day with the default interval) buries the case this log exists
    # to show and trains the operator to ignore it.
    if pressure_unrecoverable and not previously_unrecoverable:
        log.warning(
            "task_cache gc: unrecoverable disk pressure "
            "(free/total=%.3f < min=%.2f; deleted_pressure=%d "
            "active_job_dirs_skipped=%d)",
            free_after / total,
            min_free_fraction,
            deleted_pressure,
            skipped_active,
        )
    elif previously_unrecoverable and free_after_known and total > 0 and not pressure_unrecoverable:
        # The recovery notice requires the same evidence as the warning: without a
        # measurement we do not know whether the pressure eased, and declaring it
        # recovered would be the same false signal in reverse. They are two distinct
        # measurements and both are needed: `free_after_known` covers the final
        # `disk_usage`, and `total > 0` the initial one, whose failure leaves
        # `pressure_triggered` False because the pressure could not be evaluated,
        # not because it was resolved. When the recovery is not issued,
        # `prev` goes back to False and the WARNING re-arms on the next tick if the
        # pressure continues.
        log.info("task_cache gc: disk pressure recovered")

    stats = GcStats(
        scanned=scanned,
        deleted_age=deleted_age,
        deleted_pressure=deleted_pressure,
        bytes_freed_estimate=bytes_freed,
        free_before=free_before,
        free_after=free_after,
        skipped_active=skipped_active,
        pressure_unrecoverable=pressure_unrecoverable,
    )
    if deleted_age or deleted_pressure:
        log.info(
            "task_cache gc: scanned=%d deleted_age=%d deleted_pressure=%d "
            "skipped_active=%d bytes_freed~=%d free_before=%d free_after=%d",
            stats.scanned,
            stats.deleted_age,
            stats.deleted_pressure,
            stats.skipped_active,
            stats.bytes_freed_estimate,
            stats.free_before,
            stats.free_after,
        )
    return stats


def reset_other_job_caches(cache_root: Path, *, keep_job_key: str) -> ResetStats:
    """Delete all subdirectories of ``<cache_root>/tasks/`` except that of
    ``keep_job_key``. Verifies that each dir disappeared; those that persist
    (permission, lock, EBUSY) are reported in ``failed_dirs``. It does not touch
    ``<cache_root>/run/``. Tolerant of a missing ``tasks/``.

    Self-contained worker: called when each job starts to free the
    resources of the previous job. The ``keep_job_key`` dir is kept - it is the
    only reuse case: a retry of the same job after a failure.

    Unlike the GC and the flush, here the deletion is **in place**, without the
    detach. Two reasons: it runs before the job starts, so there is
    no concurrent deletion with a task writing; and its contract is to recover
    the disk synchronously (the next job starts counting on that
    space) and to expose the dir that could not be deleted. A rename always "succeeds"
    in taking the dir out of the namespace even with open files, so
    ``failed_dirs`` would always be empty and the task abort would never trigger.
    """
    tasks_root = _tasks_root(cache_root)
    if not tasks_root.exists():
        return ResetStats(dirs_deleted=0, bytes_freed_est=0, failed_dirs=())

    keep = _safe_key(keep_job_key)
    deleted = 0
    freed = 0
    failed: list[Path] = []
    for child in sorted(tasks_root.iterdir()):
        if not child.is_dir() or child.name == keep:
            continue
        # `bytes_freed_est` is best-effort: it includes bytes of dirs that failed to delete.
        freed += _delete_dir(child)
        if child.exists():
            failed.append(child)
        else:
            deleted += 1
    return ResetStats(
        dirs_deleted=deleted,
        bytes_freed_est=freed,
        failed_dirs=tuple(failed),
    )
